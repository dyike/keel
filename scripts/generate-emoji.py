#!/usr/bin/env python3
"""Generate the offline picker catalog from pinned Unicode 17.0 data."""
import argparse
import hashlib
import json
import pathlib
import re
import urllib.request

URL = "https://www.unicode.org/Public/17.0.0/emoji/emoji-test.txt"
SHA256 = "1d8a944f88d7952f7ef7c5167fef3c67995bcae24543949710231b03a201acda"
ROOT = pathlib.Path(__file__).resolve().parents[1]
TONES = ["light", "medium-light", "medium", "medium-dark", "dark"]


def generate(data):
    if hashlib.sha256(data).hexdigest() != SHA256:
        raise ValueError("Unicode source hash does not match the pinned release")
    entries = []
    group = ""
    for line in data.decode("utf-8").splitlines():
        if line.startswith("# group: "):
            group = line.removeprefix("# group: ")
        if "; fully-qualified" not in line:
            continue
        points, rest = line.split(";", 1)
        emoji = "".join(chr(int(n, 16)) for n in points.split())
        name = re.split(r" E[0-9.]+ ", rest, maxsplit=1)[1]
        entries.append([emoji, name, group, [""] * 5])
    by_name = {e[1]: e for e in entries}
    folded = set()
    for entry in entries:
        modifiers = {ord(c) - 0x1F3FA for c in entry[0] if 0x1F3FB <= ord(c) <= 0x1F3FF}
        if len(modifiers) != 1:
            continue  # mixed-tone combinations stay independently searchable
        tone = modifiers.pop()
        base_name = re.sub(r"(?:medium-light|medium-dark|light|medium|dark) skin tone", "", entry[1])
        base_name = re.sub(r":\s*,\s*", ": ", base_name)
        base_name = re.sub(r",\s*,", ",", base_name).strip(" ,:")
        base = by_name.get(base_name)
        if base is None or base[3][tone - 1]:
            continue
        base[3][tone - 1] = entry[0]
        folded.add(entry[0])
    records = [e for e in entries if e[0] not in folded]
    payload = "\n".join("\t".join([e[0], e[1], e[2], *e[3]]) for e in records)
    # A constant allows the Go linker to omit data when the default picker
    # catalog is unused. No package init parses the catalog.
    output = "// Code generated by scripts/generate-emoji.py; DO NOT EDIT.\n"
    output += "// Unicode 17.0; source SHA256: " + SHA256 + "\n"
    output += "// Unicode License V3: third_party/unicode/LICENSE.\npackage kit\n\n"
    output += "const emojiCatalogVersion = \"17.0\"\n"
    output += "const emojiCatalogSequenceCount = " + str(len(entries)) + "\n"
    output += "const emojiCatalogData = " + json.dumps(payload, ensure_ascii=False) + "\n"
    return output


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--input", type=pathlib.Path, help="cached emoji-test.txt; no network")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    data = args.input.read_bytes() if args.input else urllib.request.urlopen(URL).read()
    result = generate(data)
    target = ROOT / "ui/kit/emoji_catalog_generated.go"
    if args.check:
        if target.read_text() != result:
            raise SystemExit("generated emoji catalog differs")
    else:
        target.write_text(result)


if __name__ == "__main__":
    main()
